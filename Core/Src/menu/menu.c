//-----------------------------------------------------------------
char toUpperCase(char c)
{
	if(c >= 27 && c <= 52) // Lower case letters
	{
		return c-26;
	}
	return c;
}
//-----------------------------------------------------------------
char toLowerCase(char c)
{
	if(c >= 1 && c <= 26) // upper case letters
	{
		return c+26;
	}
	return c;
}
